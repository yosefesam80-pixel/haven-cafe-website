create table if not exists public.menu_items (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 120),
  cat text not null check (char_length(cat) between 1 and 80),
  price numeric(10, 2) not null check (price >= 0),
  img text not null,
  in_stock boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 80),
  rating smallint not null check (rating between 1 and 5),
  comment text not null check (char_length(comment) between 1 and 1200),
  created_at timestamptz not null default now(),
  approved boolean not null default false
);

create table if not exists public.haven_admins (
  user_id uuid primary key references auth.users (id) on delete cascade
);

alter table public.menu_items enable row level security;
alter table public.reviews enable row level security;
alter table public.haven_admins enable row level security;

create or replace function public.is_haven_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.haven_admins
    where user_id = (select auth.uid())
  );
$$;

revoke all on function public.is_haven_admin() from public;
grant execute on function public.is_haven_admin() to anon, authenticated;
revoke all on public.haven_admins from anon, authenticated;
grant select on public.menu_items, public.reviews to anon, authenticated;
grant insert, update, delete on public.menu_items, public.reviews to anon, authenticated;
grant usage, select on sequence public.reviews_id_seq to anon, authenticated;
grant usage, select on sequence public.menu_items_id_seq to authenticated;

drop policy if exists "Public reads available menu" on public.menu_items;
create policy "Public reads available menu"
  on public.menu_items for select to anon, authenticated
  using (in_stock or (select public.is_haven_admin()));

drop policy if exists "Admins add menu items" on public.menu_items;
create policy "Admins add menu items"
  on public.menu_items for insert to authenticated
  with check ((select public.is_haven_admin()));

drop policy if exists "Admins update menu items" on public.menu_items;
create policy "Admins update menu items"
  on public.menu_items for update to authenticated
  using ((select public.is_haven_admin()))
  with check ((select public.is_haven_admin()));

drop policy if exists "Admins delete menu items" on public.menu_items;
create policy "Admins delete menu items"
  on public.menu_items for delete to authenticated
  using ((select public.is_haven_admin()));

drop policy if exists "Public reads approved reviews" on public.reviews;
create policy "Public reads approved reviews"
  on public.reviews for select to anon, authenticated
  using (approved or (select public.is_haven_admin()));

drop policy if exists "Visitors submit pending reviews" on public.reviews;
create policy "Visitors submit pending reviews"
  on public.reviews for insert to anon, authenticated
  with check (approved = false);

drop policy if exists "Admins update reviews" on public.reviews;
create policy "Admins update reviews"
  on public.reviews for update to authenticated
  using ((select public.is_haven_admin()))
  with check ((select public.is_haven_admin()));

drop policy if exists "Admins delete reviews" on public.reviews;
create policy "Admins delete reviews"
  on public.reviews for delete to authenticated
  using ((select public.is_haven_admin()));

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'menu_items'
  ) then
    alter publication supabase_realtime add table public.menu_items;
  end if;
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'reviews'
  ) then
    alter publication supabase_realtime add table public.reviews;
  end if;
end;
$$;

